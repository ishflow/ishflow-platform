/**
 * Resolves the effective dark-mode flag for a user-chosen [ThemeMode].
 * `SYSTEM` defers to [isSystemInDarkTheme]; the explicit cases override it.
 * Pulled into a Composable helper so the call site stays declarative and
 * the existing `darkTheme: Boolean` parameter on [IshflowTheme] keeps its
 * shape — needed by snapshot tests that drive the theme directly without
 * a [ThemeMode].
 */
@Composable
private fun ThemeMode.toDarkTheme(): Boolean = when (this) {
    ThemeMode.SYSTEM -> isSystemInDarkTheme()
    ThemeMode.LIGHT -> false
    ThemeMode.DARK -> true
}

